import test from "node:test";
import assert from "node:assert/strict";
import { formatCell, generatedStamp, summarySection, toCsv, toPdf } from "../src/modules/reports/render.js";

const report = {
  heading: "Sales report - November 2026",
  summary: [{ label: "Local sales", value: 1250, type: "money" }, { label: "Open vehicles", value: 1 }, { label: "Shortage", value: -40, type: "money" }],
  sections: [
    {
      title: "Local sales",
      columns: [{ key: "customer", label: "Customer" }, { key: "total", label: "Total", type: "money" }],
      rows: [{ customer: 'Mama "Njeri", Shop', total: 1000 }, { customer: "Walk-in", total: 250 }],
      totals: { total: 1250 },
    },
    { title: "Damages", columns: [{ key: "x", label: "X" }], rows: [] },
  ],
};
const meta = { generatedBy: "Tester", generatedAt: "2026-11-08T18:24:00Z" };
const pages = (pdf) => (pdf.toString("latin1").match(/\/Type \/Page\b/g) || []).length;

test("CSV: the report header, a Summary table, then each table", () => {
  const csv = toCsv([report], meta);
  const lines = csv.replace(/^﻿/, "").split("\r\n");
  assert.deepEqual(lines.slice(0, 4), [
    "Keiyian Farmers Cooperative Society Ltd",
    "Nuru ya Jamii",
    "Sales report - November 2026",
    "\"Generated by Tester on 08 Nov 2026, 21:24 EAT\"",
  ]);
  assert.match(csv, /Summary\r\nItem,Value\r\nLocal sales,1250\r\nOpen vehicles,1\r\nShortage,-40/);
  assert.match(csv, /"Mama ""Njeri"", Shop",1000/);
  assert.match(csv, /Total,1250/);
  assert.match(csv, /No records/);
});

test("every export ends with the system-generated note and its timestamp", () => {
  const csv = toCsv([report], meta);
  assert.match(csv, /This is a system generated report\.\r\nGenerated,"08 Nov 2026, 21:24 EAT",by,Tester\r\n$/);
  assert.equal(generatedStamp(new Date("2026-11-08T18:24:00Z")), "08 Nov 2026, 21:24 EAT");
});

test("the summary is a two-column table of formatted figures", () => {
  const section = summarySection(report);
  assert.deepEqual(section.columns.map((c) => c.label), ["Item", "Value"]);
  assert.deepEqual(section.rows, [
    { item: "Local sales", value: "KES 1,250.00" },
    { item: "Open vehicles", value: "1" },
    { item: "Shortage", value: "KES -40.00" },
  ]);
});

test("PDF renders a valid document, one report per page, no blank pages", async () => {
  const pdf = await toPdf([report], meta);
  assert.equal(pdf.subarray(0, 5).toString(), "%PDF-");
  assert.equal(pages(pdf), 1);
  assert.equal(pages(await toPdf([report, report], meta)), 2);
});

test("long tables carry on over pages", async () => {
  const rows = Array.from({ length: 120 }, (_, i) => ({ customer: `Customer ${i + 1}`, total: i }));
  const long = { ...report, sections: [{ ...report.sections[0], rows }] };
  assert.ok(pages(await toPdf([long], meta)) >= 3);
});

test("cell formatting", () => {
  assert.equal(formatCell(1234.5, "money"), "1,234.50");
  assert.equal(formatCell(new Date("2026-11-06T00:00:00Z"), "date"), "06 Nov 2026");
  assert.equal(formatCell(110.25, "percent"), "110.25%");
  assert.equal(formatCell(null), "");
});
